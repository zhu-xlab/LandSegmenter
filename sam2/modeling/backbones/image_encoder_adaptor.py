    def init_prompt(self, embedding_feature, handcrafted_feature, block_num,
                    spectral_feature=None):
        B, H, W =  embedding_feature.shape[:3]
        if self.embedding_tune:
            # embedding_generator = self.embedding_generators[str(block_num)]
            embedding_generator = getattr(self, f'embedding_generator_{block_num}')
            embedding_feature = embedding_generator(embedding_feature)
    
        if self.handcrafted_tune:
            handcrafted_feature = handcrafted_feature.reshape(B, H, W, -1)
    
        if self.spectralfeat_tune:
            assert spectral_feature is not None, "Spectral feature is None while spectralfeat_tune=True!"
            # spectralfeat_generator = self.spectralfeat_generators[str(block_num)]
            spectralfeat_generator = getattr(self, f'spectralfeat_generator_{block_num}')
            spectral_feature = spectralfeat_generator(spectral_feature)
            spectral_feature = F.interpolate(spectral_feature.permute(0, 3, 1, 2), size=(H,W), mode='bilinear', align_corners=False)
            spectral_feature = spectral_feature.permute(0, 2, 3, 1)
            return handcrafted_feature, embedding_feature, spectral_feature
        else:
            return handcrafted_feature, embedding_feature

    def get_prompt(self, x, prompt, block_num, depth_num):
        concat_prompt = torch.stack(prompt, dim=-1).sum(dim=-1)
        feat = 0
        # B, H, W =  prompt[1].shape[0],  prompt[1].shape[1],  prompt[1].shape[2]
        if self.handcrafted_tune:
            # feature attention
            handcrafted_attention = getattr(self, f'handcrafted_attention_{block_num}')
            hatt = handcrafted_attention(prompt[0], concat_prompt)
            hfeat = hatt*prompt[0]  # .reshape(B, H, W, -1)
            # position/spatial attention
            handcrafted_pam = getattr(self, f'handcrafted_pam_{block_num}')
            hpatt = handcrafted_pam(hfeat)
            feat += hpatt*hfeat
        if self.embedding_tune:
            # feature attention
            embedding_attention = getattr(self, f'embedding_attention_{block_num}')
            eatt = embedding_attention(prompt[1], concat_prompt)
            efeat = eatt*prompt[1]
            # position/spatial attention
            embedding_pam = getattr(self, f'embedding_pam_{block_num}')
            epatt = embedding_pam(efeat)
            feat += epatt*efeat
        if self.spectralfeat_tune:
            # feature attention
            spectralfeat_attention = getattr(self, f'spectralfeat_attention_{block_num}')
            satt = spectralfeat_attention(prompt[2], concat_prompt)
            sfeat = satt*prompt[2]
            # position/spatial attention
            spectralfeat_pam = getattr(self, f'spectralfeat_pam_{block_num}')
            spatt = spectralfeat_pam(sfeat)
            feat += spatt*sfeat

        if self.adaptor == 'adaptor':
            lightweight_mlp = getattr(self, f'lightweight_mlp_{block_num}_{depth_num}')
            shared_mlp = getattr(self, f'shared_mlp_{block_num}')

            feat = lightweight_mlp(feat)
            feat = shared_mlp(feat)

        elif self.adaptor == 'fully_shared':
            fully_shared_mlp = getattr(self, f'fully_shared_mlp_{block_num}')
            feat = fully_shared_mlp(feat)

        elif self.adaptor == 'fully_unshared':
            fully_unshared_mlp = getattr(self, f'fully_unshared_mlp_{block_num}_{depth_num}')
            feat = fully_unshared_mlp(feat)

        x = x + feat

        return x

    def fft(self, x, rate, prompt_type):
        mask = torch.zeros(x.shape).to(x.device)
        w, h = x.shape[-2:]
        line = int((w * h * rate) ** .5 // 2)
        mask[:, :, w//2-line:w//2+line, h//2-line:h//2+line] = 1

        fft = torch.fft.fftshift(torch.fft.fft2(x, norm="forward"))

        if prompt_type == 'highpass':
            fft = fft * (1 - mask)
        elif prompt_type == 'lowpass':
            fft = fft * mask
        fr = fft.real
        fi = fft.imag

        fft_hires = torch.fft.ifftshift(torch.complex(fr, fi))
        inv = torch.fft.ifft2(fft_hires, norm="forward").real

        inv = torch.abs(inv)

        return inv


